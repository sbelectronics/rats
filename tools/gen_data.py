#!/usr/bin/env python3
"""gen_data.py - generate an ASM86 data-only module for DGROUP ranges of the original image.

usage: gen_data.py <ModName> CONST:<start>-<end> [DATA:<start>-<end>] ...   (hex DGROUP offsets)

Labels: every DGROUP name used by any module (tools/symbols.txt, src/*.sym) that no object
defines yet becomes a PUBLIC label (aliases via LABEL).  Far pointers (original relocation
entries inside the range) become  DD <public procedure>  so the linker resolves them; a far
pointer whose segment word is not relocated (e.g. absolute CTOS addresses) stays as raw bytes.
"""
import sys, os, struct, collections
T = os.path.dirname(os.path.abspath(__file__)); R = T + '/..'
sys.path.insert(0, T)
d = open(R + '/orig/Rats.run', 'rb').read(); h = struct.unpack_from('<16H', d, 0)
img = d[h[4] * 16:]; DG = 0x7A60
relocs = set()
for i in range(h[3]):
    ra, sa = struct.unpack_from('<2H', d, h[12] + 4 * i); relocs.add(sa * 16 + ra)
# public symbols defined by objects (reuse link.py layout)
src = open(T + '/link.py').read()
ns = {'__file__': T + '/link.py', '__name__': 'linkmod'}
code = src.replace("open(R + '/work/relinked.img', 'wb').write(img)", "").replace("print(", "(lambda *a, **k: None)(").replace("sys.exit('missing ' + path)", "continue")
code = code[:code.index('# ---- relocation table')]
exec(compile(code, 'link', 'exec'), ns)
defined = ns['sym']
code_pub = {}
for n, (f, o) in defined.items():
    if f != 0x7A6: code_pub[(f * 16 + o) & 0xfffff] = (n, f, o)
names = collections.defaultdict(list)   # dgroup offset -> [names]
for sf in [T + '/symbols.txt'] + [os.path.join(R, 'src', x) for x in sorted(os.listdir(R + '/src')) if x.endswith('.sym')]:
    for L in open(sf):
        L = L.split('#')[0].split()
        if len(L) >= 3 and L[1].upper() == '7A6':
            n = L[0].upper(); off = int(L[2], 16)
            if n not in defined and n not in names[off]: names[off].append(n)
mod = sys.argv[1]
ranges = []
for a in sys.argv[2:]:
    seg, r = a.split(':'); s, e = (int(x, 16) for x in r.split('-')); ranges.append((seg.upper(), s, e))
out = [f'; {mod}.asm - DGROUP data of the Rats program (generated by tools/gen_data.py from the',
       f';   original image; names are the ones the code modules use).  No code.',
       f'NAME    {mod}', '']
segs = sorted(set(s for s, _, _ in ranges), key=['CONST', 'DATA'].index)
out.append('DGROUP  GROUP   ' + ', '.join(segs))
pubs = [n for _, s, e in ranges for off in range(s, e) for n in names.get(off, [])]
for i in range(0, len(pubs), 6): out.append('        PUBLIC  ' + ', '.join(pubs[i:i + 6]))
ext = set()
body = []
for seg, s, e in ranges:
    body.append(f'{seg:8}SEGMENT WORD PUBLIC \'{seg}\'')
    off = s; pend = []
    def flush():
        global pend
        for i in range(0, len(pend), 16):
            body.append('        DB      ' + ','.join('%03XH' % b for b in pend[i:i + 16]))
        pend = []
    while off < e:
        for n in names.get(off, []):
            flush(); body.append(f'{n:15} LABEL   BYTE        ; DGROUP {off:04X}h')
        lin = DG + off
        if (lin + 2) in relocs and off + 4 <= e:
            o_, f_ = struct.unpack_from('<2H', img, lin)
            t = code_pub.get((f_ * 16 + o_) & 0xfffff)
            if t:
                flush(); body.append(f'        DD      {t[0]}'); ext.add(t[0]); off += 4; continue
            print(f'warning: reloc at {off:04X} -> {f_:04X}:{o_:04X} has no public name', file=sys.stderr)
        pend.append(img[lin]); off += 1
    flush()
    body.append(f'{seg:8}ENDS'); body.append('')
for n in sorted(ext): out.append(f'        EXTRN   {n}:FAR')
out.append('')
out += body + ['        END']
open(R + f'/src/{mod}.asm', 'w').write('\n'.join(out) + '\n')
print(f'wrote src/{mod}.asm: {len(pubs)} public labels, {len(ext)} far pointers')
